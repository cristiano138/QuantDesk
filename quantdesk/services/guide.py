_SLUG_INDEX = {t["slug"]: t for t in TERMS}


def _validate() -> None:
    """启动自检：slug 唯一、分类存在、related 指向真实 slug。

    术语库是手写数据表，最怕的是复制粘贴时留下的悬空引用——这里直接 fail fast。
    """
    cats = {c["id"] for c in CATEGORIES}
    seen: set[str] = set()
    for t in TERMS:
        if t["slug"] in seen:
            raise ValueError(f"术语 slug 重复: {t['slug']}")
        seen.add(t["slug"])
        if t["category"] not in cats:
            raise ValueError(f"术语 {t['slug']} 的分类不存在: {t['category']}")
    for t in TERMS:
        for r in t["related"]:
            if r not in _SLUG_INDEX:
                raise ValueError(f"术语 {t['slug']} 的 related 指向不存在的 slug: {r}")


_validate()


def _hit_count(text: str, needle: str) -> int:
    return text.count(needle)


def categories() -> list[dict]:
    """分类清单（含每类术语数量）。"""
    counts: dict[str, int] = {}
    for t in TERMS:
        counts[t["category"]] = counts.get(t["category"], 0) + 1
    return [{**c, "count": counts.get(c["id"], 0)} for c in CATEGORIES]


def terms(category: str | None = None, q: str | None = None) -> list[dict]:
    """按分类与关键词筛术语；关键词命中数多的排在前面。"""
    out = [t for t in TERMS if not category or t["category"] == category]
    key = (q or "").strip().lower()
    if key:
        scored = []
        for t in out:
            hay = " ".join([t["term"], t["one_liner"], t["explain"], t["example"],
                             " ".join(t["aliases"]), t["where_to_see"]]).lower()
            if key in hay:
                scored.append((_hit_count(hay, key) + (5 if key in t["term"].lower() else 0), t))
        scored.sort(key=lambda x: -x[0])
        return [t for _, t in scored]
    return out


def get_term(slug: str) -> dict | None:
    """按 slug 取术语详情；related 附上名称，前端可直接渲染跳转。"""
    t = _SLUG_INDEX.get((slug or "").strip())
    if t is None:
        return None
    related = [{"slug": r, "term": _SLUG_INDEX[r]["term"]} for r in t["related"]]
    return {**t, "related_terms": related}
