"""应用内使用手册：每个板块一份「怎么用」的说明书。

为什么要这个模块：新用户打开软件看到的是一堆界面和术语，不知道每个页面干什么、
要准备什么才会动。README 与 docs/ 是给开发者的，用户在运行时读不到——所以说明书必须
做成后端结构化数据 + 前端可读页面（/manual），并让每个板块标题上都有入口。

写作纪律（给后续改内容的人）：
1. **只写代码里真实存在的东西**：字段名、提示原文、配置默认值都要能追溯到出处；
   不确定就写「待实测」，不许写「理论上应该」。
2. **前置条件必须可自查**：每条 ready 要告诉用户「怎么判断自己满足了没有」，不只列要求。
3. **errors 是对着界面/后端原文抄的**——用户看到那句话时能查到含义与处置，这是本模块主要价值。
4. **gotchas 专治「以为是 A 其实是 B」**：口径与设计意图类误解（买卖量主口径、港股单源、
   腾讯无成交额、mode 不等于资金路由、回测明细不落库）必须写在这里。
5. 正文内层引用一律用「」——在双引号字符串里再放 ASCII 双引号会把 Python 字符串截断，
   本文件第一版就是这么炸的。
"""

