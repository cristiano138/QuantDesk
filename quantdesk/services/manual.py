# 内容型数据（和术语表同一类）：写坏了不会报错，只会静默缺章节，所以 import 期钉住结构。

_ROUTES = {"/", "/watch", "/market", "/backtest", "/monitor", "/channels",
           "/interop", "/data", "/compliance", "/settings", "/guide", "/manual"}


def _validate() -> None:
    seen: set[str] = set()
    for s in SECTIONS:
        if s.slug in seen:
            raise ValueError(f"手册重复 slug: {s.slug}")
        seen.add(s.slug)
        if not (s.title and s.summary and s.intro):
            raise ValueError(f"手册 {s.slug} 缺标题/简介/说明")
        if s.group not in GROUPS:
            raise ValueError(f"手册 {s.slug} 分组非法: {s.group}")
        if s.route not in _ROUTES:
            raise ValueError(f"手册 {s.slug} 的 route 不是已知页面: {s.route}")
        if not s.steps:
            raise ValueError(f"手册 {s.slug} 没有操作步骤")
        for p in s.prerequisites:
            if not p.ready:
                raise ValueError(f"手册 {s.slug} 前置「{p.what[:20]}」没有自查方法")
        for e in s.errors:
            if not e.meaning or not e.fix:
                raise ValueError(f"手册 {s.slug} 提示「{e.text[:20]}」缺含义或处置")
        for lk in s.links:
            base = lk.to.split("?")[0]
            if base.startswith("/") and base not in _ROUTES:
                raise ValueError(f"手册 {s.slug} 站内链接指向未知路径: {lk.to}")


_validate()
