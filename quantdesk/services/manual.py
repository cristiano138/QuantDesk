_TERM_N = len(_guide.TERMS)
_CAT_N = len(_guide.CATEGORIES)


@dataclass(frozen=True)
class Prereq:
    what: str     # 需要准备什么
    why: str      # 不准备会怎样
    where: str    # 在哪设置（含站内路径）
    ready: str    # 怎么自查已经满足了


@dataclass(frozen=True)
class Step:
    do: str
    expect: str


@dataclass(frozen=True)
class Readout:
    field: str
    meaning: str


@dataclass(frozen=True)
class Gotcha:
    myth: str
    truth: str


@dataclass(frozen=True)
class ErrTip:
    text: str     # 界面或后端返回原文
    meaning: str
    fix: str


@dataclass(frozen=True)
class Faq:
    q: str
    a: str


@dataclass(frozen=True)
class Link:
    label: str
    to: str


@dataclass(frozen=True)
class Section:
    slug: str
    title: str
    group: str
    nav: str
    route: str
    summary: str
    status: str
    intro: str
    prerequisites: tuple[Prereq, ...] = ()
    steps: tuple[Step, ...] = ()
    readouts: tuple[Readout, ...] = ()
    gotchas: tuple[Gotcha, ...] = ()
    errors: tuple[ErrTip, ...] = ()
    faq: tuple[Faq, ...] = ()
    links: tuple[Link, ...] = ()

    def to_dict(self) -> dict:
        return asdict(self)

    def haystack(self) -> str:
        """检索用拼平文本（含提示原文：用户常是「照着那句话搜」进来的）。"""
        parts = [self.title, self.nav, self.summary, self.intro]
        parts += [f"{p.what} {p.why} {p.where} {p.ready}" for p in self.prerequisites]
        parts += [f"{s.do} {s.expect}" for s in self.steps]
        parts += [f"{r.field} {r.meaning}" for r in self.readouts]
        parts += [f"{g.myth} {g.truth}" for g in self.gotchas]
        parts += [f"{e.text} {e.meaning} {e.fix}" for e in self.errors]
        parts += [f"{f_.q} {f_.a}" for f_ in self.faq]
        return " ".join(parts)


