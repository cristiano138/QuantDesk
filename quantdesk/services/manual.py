# ================================================================ 查询接口

def sections() -> list[dict]:
    """目录：界面渲染左侧列表用。"""
    return [{"slug": s.slug, "title": s.title, "route": s.route, "nav": s.nav,
             "summary": s.summary, "group": s.group} for s in SECTIONS]


def get_section(slug: str) -> dict | None:
    for s in SECTIONS:
        if s.slug == slug:
            return s.to_dict()
    return None


def search(q: str, limit: int = 12) -> list[dict]:
    """检索：手册常被「我界面上看到那句话怎么办」这样打开，所以提示原文也要能命中。"""
    key = (q or "").strip().lower()
    if not key:
        return []
    tokens = [t for t in re.split(r"\s+", key) if t]
    hits: list[dict] = []
    for s in SECTIONS:
        hay = s.haystack().lower()
        score = sum(hay.count(t) for t in tokens)
        if score <= 0:
            continue
        field_name, snippet = _best_field(s, tokens)
        hits.append({"slug": s.slug, "title": s.title, "field": field_name,
                     "snippet": snippet, "score": score})
    hits.sort(key=lambda h: -h["score"])
    return hits[:limit]


def _best_field(sec: Section, tokens: list[str]) -> tuple[str, str]:
    """挑一个最能解释「为什么命中」的字段返回，附上下文片段。"""
    candidates: list[tuple[str, str]] = [("简介", sec.summary), ("说明", sec.intro)]
    candidates += [("前置：" + p.what, f"{p.why}｜在哪设置：{p.where}") for p in sec.prerequisites]
    candidates += [("操作步骤", f"{s.do} → {s.expect}") for s in sec.steps]
    candidates += [("界面读法", f"{r.field}：{r.meaning}") for r in sec.readouts]
    candidates += [("常见误解", f"{g.myth} → {g.truth}") for g in sec.gotchas]
    candidates += [("提示原文：" + e.text, f"{e.meaning}｜处置：{e.fix}") for e in sec.errors]
    candidates += [("问答：" + f_.q, f_.a) for f_ in sec.faq]
    best, best_score = ("简介", sec.summary), -1
    for name, text in candidates:
        # 名字也进打分：提示原文就写在前缀里（"提示原文：xxx"），只比正文会让
        # 「照着那句话搜」的用户命中了章节却显示成「简介」——检索结果对不上来意
        low = f"{name} {text}".lower()
        score = sum(low.count(t) for t in tokens)
        if score > best_score:
            best, best_score = (name, text), score
    return best[0], best[1][:200]


